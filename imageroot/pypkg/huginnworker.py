"""Background worker settings of the Huginn module.

Huginn runs its scheduler and one Delayed Job worker in the threaded "jobs"
process (Procfile); more Delayed Job workers are extra "djN" lines. Huginn
reads the limits from the environment (config/initializers/delayed_job.rb,
config/database.yml). The health check (bin/huginn-healthcheck) restarts a
worker that stopped processing jobs.
"""

import os

import agent

# name: (environment key, default, minimum, maximum)
WORKER = {
    "delayed_job_max_runtime": ("DELAYED_JOB_MAX_RUNTIME", 15, 2, 60),   # minutes
    "delayed_job_sleep_delay": ("DELAYED_JOB_SLEEP_DELAY", 10, 1, 60),   # seconds
    "database_pool": ("DATABASE_POOL", 20, 5, 100),
    "delayed_job_workers": ("DELAYED_JOB_WORKERS", 1, 1, 5),
    "healthcheck_minutes": ("HEALTHCHECK_MINUTES", 30, 10, 1440),
    "healthcheck_backlog": ("HEALTHCHECK_BACKLOG", 20, 1, 100000),
}
HEALTHCHECK_MODES = ("off", "restart", "quiet")
DEFAULT_MODE = "restart"


def current():
    """Settings as stored in the environment (defaults for missing keys)."""
    out = {}
    for name, (key, default, low, high) in WORKER.items():
        try:
            out[name] = min(high, max(low, int(os.environ.get(key) or default)))
        except ValueError:
            out[name] = default
    mode = os.environ.get("HEALTHCHECK_MODE") or DEFAULT_MODE
    out["healthcheck_mode"] = mode if mode in HEALTHCHECK_MODES else DEFAULT_MODE
    out["healthcheck_mail_to"] = os.environ.get("HEALTHCHECK_MAIL_TO", "")
    return out


def validate(data):
    """[(field, error)] for a configure-module request."""
    errors = []
    for name, (_key, _default, low, high) in WORKER.items():
        if name in data:
            value = data[name]
            if not isinstance(value, int) or isinstance(value, bool) or not low <= value <= high:
                errors.append((name, "value_out_of_range"))
    if "healthcheck_mode" in data and data["healthcheck_mode"] not in HEALTHCHECK_MODES:
        errors.append(("healthcheck_mode", "invalid_value"))
    mail = (data.get("healthcheck_mail_to") or "").strip()
    if mail and ("@" not in mail or any(c.isspace() for c in mail) or len(mail) > 254):
        errors.append(("healthcheck_mail_to", "invalid_email"))
    return errors


def _set(key, value):
    agent.set_env(key, value)
    os.environ[key] = value


def apply(data):
    """Store the settings of a request; keys not sent keep their value."""
    for name, (key, default, _low, _high) in WORKER.items():
        if name in data:
            _set(key, str(int(data[name])))
        elif not os.environ.get(key):
            _set(key, str(default))
    if "healthcheck_mode" in data:
        _set("HEALTHCHECK_MODE", data["healthcheck_mode"])
    elif not os.environ.get("HEALTHCHECK_MODE"):
        _set("HEALTHCHECK_MODE", DEFAULT_MODE)
    if "healthcheck_mail_to" in data:
        _set("HEALTHCHECK_MAIL_TO", (data.get("healthcheck_mail_to") or "").strip())


def write_procfile(path, workers):
    """The Procfile of the container: web, the threaded jobs process (one
    Delayed Job worker) and workers-1 additional Delayed Job workers."""
    lines = [
        "# Generated by the Huginn module (DELAYED_JOB_WORKERS). Do not edit by hand.",
        "web: bundle exec puma -C config/puma.rb",
        "jobs: bundle exec rails runner bin/threaded.rb",
    ]
    lines += [f"dj{i}: bundle exec script/delayed_job -i {i} run" for i in range(2, int(workers) + 1)]
    tmp = path + ".tmp"
    with open(tmp, "w") as fp:
        fp.write("\n".join(lines) + "\n")
    os.replace(tmp, path)
